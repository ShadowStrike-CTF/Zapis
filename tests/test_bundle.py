# --- route ------------------------------------------------------------------------------------

@pytest.mark.parametrize("fmt, media", [
    ("md", "text/markdown"), ("html", "text/html"), ("pdf", "application/pdf"), ("zip", "application/zip"),
])
def test_route_bundle_formats(client, fmt, media):
    r = client.post(URL + fmt, json={"writeups": ENTRIES})
    assert r.status_code == 200
    assert r.headers["content-type"].startswith(media)
    assert r.headers["content-disposition"] == f'attachment; filename="dfir-cup-2026-writeups.{fmt}"'


def test_route_zip_inner(client):
    r = client.post(URL + "zip", json={"writeups": ENTRIES, "inner": "html"})
    assert r.status_code == 200
    assert "lost-usb.html" in zipfile.ZipFile(io.BytesIO(r.content)).namelist()


def test_route_422_names_failing_entry_and_sends_no_file(client):
    r = client.post(URL + "pdf", json={"writeups": [ENTRIES[0], entry("Broken", "")]})
    assert r.status_code == 422
    assert "content-disposition" not in r.headers
    assert r.json()["detail"].startswith("Writeup 2 (Broken):")
    assert "flag" in r.json()["detail"]


@pytest.mark.parametrize("body", [{}, {"writeups": []}, {"writeups": ENTRIES, "inner": "docx"}])
def test_route_bad_bodies_422(client, body):
    fmt = "zip" if "inner" in body else "md"
    assert client.post(URL + fmt, json=body).status_code == 422


def test_route_unknown_format_422(client):
    assert client.post(URL + "docx", json={"writeups": ENTRIES}).status_code == 422


# --- CLI --------------------------------------------------------------------------------------

def write_draft(path, writeups):
    path.write_text(json.dumps({"tool": "zapis", "draft_version": "1.0", "active_index": 0,
                                "writeups": writeups}), encoding="utf-8")
    return path


def test_cli_bundle_writes_file(tmp_path, capsys):
    draft = write_draft(tmp_path / "d.zapis.json", ENTRIES)
    out = tmp_path / "all.md"
    assert cli.main(["bundle", str(draft), "--format", "md", "-o", str(out)]) == 0
    text = out.read_text(encoding="utf-8")
    assert all(e["flag"] in text for e in ENTRIES)
    assert str(out) in capsys.readouterr().out


def test_cli_bundle_zip_default_name(tmp_path, monkeypatch):
    draft = write_draft(tmp_path / "d.zapis.json", ENTRIES)
    monkeypatch.chdir(tmp_path)
    assert cli.main(["bundle", str(draft), "--format", "zip", "--inner", "html"]) == 0
    names = zipfile.ZipFile(tmp_path / "dfir-cup-2026-writeups.zip").namelist()
    assert "lost-usb.html" in names and "index.md" in names


def test_cli_bundle_invalid_entry_writes_nothing(tmp_path, capsys):
    draft = write_draft(tmp_path / "d.zapis.json", [ENTRIES[0], entry("Bad", "f", difficulty=9)])
    out = tmp_path / "x.pdf"
    assert cli.main(["bundle", str(draft), "--format", "pdf", "-o", str(out)]) == 1
    assert "error: Writeup 2 (Bad):" in capsys.readouterr().err
    assert not out.exists()


@pytest.mark.parametrize("content, message", [
    ("{not json", "not valid JSON"),
    ('{"tool": "sarissa", "writeups": []}', "tool"),
])
def test_cli_bundle_bad_draft(tmp_path, capsys, content, message):
    draft = tmp_path / "d.zapis.json"
    draft.write_text(content, encoding="utf-8")
    assert cli.main(["bundle", str(draft), "--format", "md", "-o", str(tmp_path / "o.md")]) == 1
    assert message in capsys.readouterr().err


def test_cli_bundle_missing_file(tmp_path, capsys):
    assert cli.main(["bundle", str(tmp_path / "nope.json"), "--format", "md"]) == 1
    assert "cannot read" in capsys.readouterr().err



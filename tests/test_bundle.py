from __future__ import annotations

import io
import json
import subprocess
import sys
import zipfile

import pytest
from fastapi.testclient import TestClient

from zapis import cli
from zapis.core.bundle import BundleError, bundle_filename, export_bundle
from zapis.main import create_app

URL = "/api/export/bundle/"


def entry(name, flag, **overrides):
    return {"challenge_name": name, "ctf_name": "DFIR-Cup-2026", "category": "Forensics",
            "difficulty": 2, "tools_used": ["photorec"], "approach": f"Solved {name} <carefully>.",
            "flag": flag, "notes": "", "author": "R", "date": "2026-11-05",
            "time_spent_minutes": 0, **overrides}


ENTRIES = [entry("Lost USB", "flag{usb}"), entry("Phish Tank", "flag{phish}"),
           entry("Cold Case", "flag{cold}")]


@pytest.fixture
def client():
    return TestClient(create_app())


# --- formats ------------------------------------------------------------------------

@pytest.mark.parametrize("fmt", ["md", "html"])
def test_text_bundles_contain_every_name_and_flag(fmt):
    text = export_bundle(ENTRIES, fmt).decode("utf-8")
    for e in ENTRIES:
        assert e["challenge_name"] in text and e["flag"] in text
    assert text.count("Generated by Zapis") == 1


def test_html_bundle_layout_and_escaping():
    html = export_bundle(ENTRIES, "html").decode("utf-8")
    assert html.count('<article class="writeup"') == 3
    assert ".writeup { break-before: page;" in html
    assert "white-space: pre-wrap;" in html and "word-break: break-all;" in html
    assert "&lt;carefully&gt;" in html and "<carefully>" not in html
    assert 'href="#writeup-2">Phish Tank</a>' in html


def test_md_bundle_contents_list():
    md = export_bundle(ENTRIES, "md").decode("utf-8")
    assert "## Contents\n1. Lost USB — Forensics\n2. Phish Tank — Forensics\n3. Cold Case — Forensics\n" in md


def test_pdf_bundle_one_document_new_page_per_writeup():
    import weasyprint
    assert export_bundle(ENTRIES, "pdf").startswith(b"%PDF")
    # The PDF is written from this HTML; lay it out to see where pages break.
    doc = weasyprint.HTML(string=export_bundle(ENTRIES, "html").decode("utf-8")).render()
    assert len(doc.pages) == 1 + len(ENTRIES)  # title/contents page + one page per writeup


def test_pdf_bundle_calls_write_pdf_once(monkeypatch):
    import weasyprint
    calls = []
    real = weasyprint.HTML.write_pdf
    monkeypatch.setattr(weasyprint.HTML, "write_pdf",
                        lambda self, *a, **k: calls.append(1) or real(self, *a, **k))
    export_bundle(ENTRIES, "pdf")
    assert calls == [1]


def test_pdf_bundle_long_code_line_wraps():
    long_line = "A" * 600
    pdf = export_bundle([entry("Wide", "flag{w}", approach=f"```\n{long_line}\n```")], "pdf")
    assert pdf.startswith(b"%PDF")
    html = export_bundle([entry("Wide", "flag{w}", approach=f"```\n{long_line}\n```")], "html").decode()
    assert f"<pre><code>{long_line}</code></pre>" in html


# --- title ---------------------------------------------------------------------------

def test_common_ctf_name_is_title():
    md = export_bundle(ENTRIES, "md").decode("utf-8")
    assert md.startswith("# DFIR-Cup-2026\n")
    assert "<h1>DFIR-Cup-2026</h1>" in export_bundle(ENTRIES, "html").decode("utf-8")


def test_mixed_ctf_names_get_generic_title():
    mixed = [ENTRIES[0], entry("Other", "flag{o}", ctf_name="Another CTF")]
    assert export_bundle(mixed, "md").decode("utf-8").startswith("# CTF Writeups\n")
    assert "<h1>CTF Writeups</h1>" in export_bundle(mixed, "html").decode("utf-8")
    assert bundle_filename(mixed, "md") == "writeups.md"


# --- zip ------------------------------------------------------------------------------

def test_zip_one_file_per_entry_plus_index():
    zf = zipfile.ZipFile(io.BytesIO(export_bundle(ENTRIES, "zip")))
    assert sorted(zf.namelist()) == ["cold-case.md", "index.md", "lost-usb.md", "phish-tank.md"]
    assert "flag{phish}" in zf.read("phish-tank.md").decode("utf-8")
    index = zf.read("index.md").decode("utf-8")
    assert "1. [Lost USB](lost-usb.md) — Forensics" in index
    assert "flag{usb}" not in index  # contents only


def test_zip_slug_collisions():
    dupes = [entry("Same Name", "flag{1}"), entry("same name!", "flag{2}"),
             entry("Same-Name", "flag{3}"), entry("Same Name 2", "flag{4}")]
    names = zipfile.ZipFile(io.BytesIO(export_bundle(dupes, "zip", "html"))).namelist()
    assert names[:4] == ["same-name.html", "same-name-2.html", "same-name-3.html", "same-name-2-2.html"]


def test_zip_inner_pdf_entries_are_pdfs():
    zf = zipfile.ZipFile(io.BytesIO(export_bundle(ENTRIES[:2], "zip", "pdf")))
    pdfs = [n for n in zf.namelist() if n.endswith(".pdf")]
    assert len(pdfs) == 2
    for name in pdfs:
        assert zf.read(name).startswith(b"%PDF")


# --- validation: all-or-nothing ---------------------------------------------------------------

def test_invalid_entry_names_index_and_name():
    bad = [ENTRIES[0], entry("Phish Tank", "flag{p}", difficulty=0),
           entry("", "  ", category="Hardware")]
    with pytest.raises(BundleError) as exc:
        export_bundle(bad, "md")
    msgs = exc.value.messages
    assert len(msgs) == 2
    assert msgs[0].startswith("Writeup 2 (Phish Tank):") and "difficulty" in msgs[0]
    assert msgs[1].startswith("Writeup 3 ((unnamed)):") and "category" in msgs[1]


def test_bundle_never_renders_when_invalid(monkeypatch):
    import zapis.core.bundle as bundle
    monkeypatch.setattr(bundle, "_render_md", lambda *a, **k: pytest.fail("rendered"))
    with pytest.raises(BundleError):
        bundle.export_bundle([ENTRIES[0], {"challenge_name": "x"}], "md")


